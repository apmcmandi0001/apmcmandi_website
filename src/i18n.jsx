export const dictionaries = { mr, hi, en }
export const languages = [
  { code: 'mr', label: 'मराठी' },
  { code: 'hi', label: 'हिंदी' },
  { code: 'en', label: 'EN' },
]

const LangContext = createContext({ lang: 'mr', t: mr, setLang: () => {} })

export function LangProvider({ children }) {
  const [lang, setLangState] = useState(() => {
    try {
      const saved = localStorage.getItem('lang')
      return saved && dictionaries[saved] ? saved : 'mr'
    } catch {
      return 'mr'
    }
  })

  const setLang = (l) => {
    setLangState(l)
    try {
      localStorage.setItem('lang', l)
    } catch {
      /* ignore */
    }
  }

  useEffect(() => {
    document.documentElement.lang = lang
  }, [lang])

  return <LangContext.Provider value={{ lang, t: dictionaries[lang], setLang }}>{children}</LangContext.Provider>
}

export const useLang = () => useContext(LangContext)
